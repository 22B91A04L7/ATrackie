const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../src/utils/apiRequest.js'), 'utf8').replace('export async function', 'async function');
let response;
const context = { AbortSignal, URL, fetch: async () => { if (response instanceof Error) throw response; return response; } };
vm.createContext(context); vm.runInContext(source, context);
const call = () => context.apiRequest('http://localhost:5000/api/jobs');
(async () => {
  response = new Error('offline');
  await assert.rejects(call(), /Could not reach/);
  response = {status: 502, ok: false, json: async () => { throw new SyntaxError(); }};
  await assert.rejects(call(), /HTTP 502/);
  response.status = 401;
  const unauthorized = await call();
  assert.equal(unauthorized.status, 401);
  assert.match((await unauthorized.json()).error, /sign in/);
  response = {status: 429, ok: false, json: async () => ({error: 'Try again in 60 seconds'})};
  await assert.rejects(call(), /60 seconds/);
  response = {status: 200, ok: true, json: async () => ({})};
  await assert.rejects(call(), /incomplete/);
  response.json = async () => ({jobs: []});
  assert.equal((await (await call()).json()).jobs.length, 0);
  context.localStorage = {getItem: () => 'new-session'};
  response = {status: 401, ok: false, json: async () => ({error: 'expired'})};
  await assert.rejects(context.apiRequest('http://localhost:5000/api/jobs', {headers: {Authorization: 'Bearer old-session'}}), /account changed/);
  let active = 'old-session';
  context.localStorage.getItem = () => active;
  response.json = async () => { active = 'new-session'; return {error: 'expired'}; };
  await assert.rejects(context.apiRequest('http://localhost:5000/api/jobs', {headers: {Authorization: 'Bearer old-session'}}), /account changed/);
  const deadline = {aborted: false};
  context.AbortSignal = {timeout(ms) {assert.equal(ms, 30000); return deadline;}};
  context.fetch = async () => {deadline.aborted = true; throw new Error('aborted');};
  await assert.rejects(call(), /timed out/);
  deadline.aborted = false;
  context.fetch = async () => ({status: 200, ok: true, json: async () => {deadline.aborted = true; throw new Error('aborted');}});
  await assert.rejects(call(), /response timed out/);
  console.log('PASS stale sessions before/after body parsing and request/body deadlines');
  console.log('PASS dashboard offline, non-JSON errors, non-JSON 401, rate-limit text, incomplete and valid data');
})().catch(error => { console.error(error); process.exitCode = 1; });
